#!/usr/bin/env python3
"""Render front/cover.tex, front/titlekor.tex and front/signature.tex from
thesis.json. Run after editing thesis.json. scripts/build.sh invokes this
automatically. Stdlib only (Python 3.8+).

Validation enforces the Yonsei 2026 spec:
- degree_month must be February or August
- degree_level must be master or doctoral
- supervisors[] non-empty, each {name, title}
- committee[] has exactly 3 entries for master, 5 for doctoral; first
  role=chair, the rest role=member; titles are all "Prof." or all "Dr."
  (or all empty), names non-empty
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "thesis.json"
COVER_TEMPLATE = ROOT / "front" / "cover.tex.in"
COVER_OUT = ROOT / "front" / "cover.tex"
TITLEKOR_OUT = ROOT / "front" / "titlekor.tex"
SIGNATURE_TEMPLATE = ROOT / "front" / "signature.tex.in"
SIGNATURE_OUT = ROOT / "front" / "signature.tex"

GENERATED_HEADER = (
    "% GENERATED by scripts/render_metadata.py from thesis.json.\n"
    "% DO NOT EDIT — changes will be overwritten on next build.\n"
)

REQUIRED_KEYS = (
    "title",
    "title_kor",
    "author",
    "department",
    "degree",
    "degree_month",
    "degree_year",
    "supervisors",
    "committee",
)

# Wording for the title page ("A <X> Submitted ...") and signature page
# ("the <Y> of [name] is approved.") per Yonsei 2026 spec samples.
LEVEL_WORDING = {
    "master":   {"title": "Master's Thesis", "lower": "master's thesis"},
    "doctoral": {"title": "Dissertation",    "lower": "dissertation"},
}

# Required committee size by degree_level per Yonsei 2026 spec.
COMMITTEE_SIZE = {"master": 3, "doctoral": 5}

ALLOWED_TITLES = ("Prof.", "Dr.", "")


def fail(msg: str) -> "None":
    print(f"render_metadata: error: {msg}", file=sys.stderr)
    sys.exit(1)


def load_config() -> dict:
    if not CONFIG.exists():
        fail(f"{CONFIG.relative_to(ROOT)} not found")
    try:
        data = json.loads(CONFIG.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        fail(f"{CONFIG.relative_to(ROOT)} is not valid JSON: {exc}")

    # Required-field presence first — fail fast if anything mandatory is missing.
    missing = [k for k in REQUIRED_KEYS if k not in data]
    if missing:
        fail(f"thesis.json missing required keys: {', '.join(missing)}")

    # Spec-level constraints checked before any optional defaults so that
    # invalid spec values are reported regardless of degree_level handling.
    if data["degree_month"] not in ("February", "August"):
        fail(
            f"degree_month must be 'February' or 'August' per Yonsei 2026 "
            f"spec; got {data['degree_month']!r}"
        )

    if not isinstance(data["supervisors"], list) or not data["supervisors"]:
        fail("'supervisors' must be a non-empty list")
    for i, sup in enumerate(data["supervisors"]):
        if not isinstance(sup, dict) or "name" not in sup or "title" not in sup:
            fail(f"supervisors[{i}] needs 'name' and 'title'")

    # degree_level is optional — default to master after strict checks pass.
    level = data.setdefault("degree_level", "master")
    if level not in LEVEL_WORDING:
        fail(
            f"degree_level must be one of {sorted(LEVEL_WORDING)}, got {level!r}"
        )

    validate_committee(data["committee"], level)
    return data


def validate_committee(committee, level: str) -> None:
    if not isinstance(committee, list):
        fail("'committee' must be a list")
    expected = COMMITTEE_SIZE[level]
    if len(committee) != expected:
        fail(
            f"committee must have exactly {expected} entries for "
            f"degree_level={level!r}; got {len(committee)}"
        )
    for i, m in enumerate(committee):
        if not isinstance(m, dict):
            fail(f"committee[{i}] must be an object")
        for key in ("role", "title", "name"):
            if key not in m:
                fail(f"committee[{i}] missing key {key!r}")
        if not m["name"]:
            fail(f"committee[{i}].name must be non-empty")
    if committee[0]["role"] != "chair":
        fail("committee[0].role must be 'chair'")
    for i, m in enumerate(committee[1:], start=1):
        if m["role"] != "member":
            fail(f"committee[{i}].role must be 'member' (only [0] is chair)")

    titles = {m["title"] for m in committee}
    bad = titles - set(ALLOWED_TITLES)
    if bad:
        fail(
            f"committee titles must be 'Prof.', 'Dr.' or empty; got {sorted(bad)}"
        )
    if len(titles) > 1:
        fail(
            f"committee titles must all be the same value (no mixing "
            f"Prof./Dr.); got {sorted(titles)}"
        )


def render_cover(data: dict) -> str:
    template = COVER_TEMPLATE.read_text(encoding="utf-8")
    supervisor_block = "\n".join(
        f"\\supervisor{{{s['name']}}}{{{s['title']}}}"
        for s in data["supervisors"]
    )
    wording = LEVEL_WORDING[data["degree_level"]]
    tokens = {
        "@@TITLE@@": data["title"],
        "@@AUTHOR@@": data["author"],
        "@@DEPARTMENT@@": data["department"],
        "@@DEGREE@@": data["degree"],
        "@@DEGREE_MONTH@@": data["degree_month"],
        "@@DEGREE_YEAR@@": str(data["degree_year"]),
        "@@SUPERVISOR_BLOCK@@": supervisor_block,
        "@@THESIS_TYPE_TITLE@@": wording["title"],
        "@@THESIS_TYPE_LOWER@@": wording["lower"],
    }
    rendered = template
    for token, value in tokens.items():
        rendered = rendered.replace(token, value)
    leftover = [t for t in tokens if t in rendered]
    if leftover:
        fail(f"unsubstituted tokens in cover.tex.in: {leftover}")
    return GENERATED_HEADER + rendered


def render_titlekor(data: dict) -> str:
    # titlekor.tex is \input inside the CJK environment in main.tex, so the
    # Korean characters are tokenized with the nanummj font active.
    return (
        GENERATED_HEADER
        + f"\\newcommand{{\\titlekor}}{{{data['title_kor']}}}\n"
    )


ROLE_LABEL = {"chair": "Committee Chair", "member": "Committee Member"}


def render_signature(data: dict) -> str:
    template = SIGNATURE_TEMPLATE.read_text(encoding="utf-8")
    blocks = []
    for i, m in enumerate(data["committee"]):
        role = ROLE_LABEL[m["role"]]
        # Title prefix uses LaTeX backslash-space for inter-word spacing
        # (so "Prof." stays adjacent to the name without a sentence-end gap).
        signer = f"{m['title']}\\ {m['name']}" if m["title"] else m["name"]
        block = f"\\signature{{{role}}}{{{signer}}}"
        blocks.append(block)
    # Separate blocks with \par + \vskip so the rubber-spaced \vfill markers
    # in signature.tex.in distribute remaining vertical space evenly. The
    # 25pt minimum keeps blocks visually distinct even when \vfill flexes.
    committee_blocks = "\n\\par\\vskip 25pt\n".join(blocks)
    rendered = template.replace("@@COMMITTEE_BLOCKS@@", committee_blocks)
    if "@@COMMITTEE_BLOCKS@@" in rendered:
        fail("signature.tex.in did not consume @@COMMITTEE_BLOCKS@@")
    return GENERATED_HEADER + rendered


def main() -> int:
    data = load_config()
    COVER_OUT.write_text(render_cover(data), encoding="utf-8")
    TITLEKOR_OUT.write_text(render_titlekor(data), encoding="utf-8")
    SIGNATURE_OUT.write_text(render_signature(data), encoding="utf-8")
    print(
        f"rendered {COVER_OUT.relative_to(ROOT)}, "
        f"{TITLEKOR_OUT.relative_to(ROOT)}, "
        f"{SIGNATURE_OUT.relative_to(ROOT)}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
